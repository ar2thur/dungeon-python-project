class Item:
    def __init__(self, name, description, rarity):
        self.name = name
        self.description = description
        self.rarity = rarity
    
    def getName(self):
        return self.name
    
    def getDescription(self):
        return self.description
    
    def getRarity(self):
        return self.rarity
    
    
    
    
    
    
    
    
    